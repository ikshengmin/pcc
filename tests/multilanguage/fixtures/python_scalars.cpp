// Independent C++ source provider for the compiled-Python scalar ABI gate.
extern "C" long long python_cpp_mix(long long a, long long b, long long c,
                                   long long d, long long e, long long f,
                                   long long g, long long h) {
    return a - b - 2*c - 3*d - 4*e - 5*f - 6*g - 7*h;
}
