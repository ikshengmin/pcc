"""Tiny test-only class writer, independently authored from JVMS 4.

Not a source compiler and not part of the AOT targetchain. Fixtures describe
literal instructions; no javac-generated bytes or third-party test corpus.
"""
import struct


def u2(value):
    return struct.pack(">H", value)


def u4(value):
    return struct.pack(">I", value)


class ClassBuilder:
    def __init__(self, name="Example", *, major=49):
        self.pool = []
        self.major = major
        self.name = name
        self.this = self.class_(name)
        self.super = self.class_("java/lang/Object")
        self.code_name = self.utf8("Code")
        self.methods = []

    def add(self, data):
        self.pool.append(data)
        return len(self.pool)

    def utf8(self, text):
        raw = text.encode("utf-8")
        return self.add(b"\x01" + u2(len(raw)) + raw)

    def class_(self, name):
        return self.add(b"\x07" + u2(self.utf8(name)))

    def integer(self, value):
        return self.add(b"\x03" + struct.pack(">i", value))

    def method_ref(self, name, descriptor="()I", owner=None):
        cls = self.this if owner is None else self.class_(owner)
        pair = self.add(b"\x0c" + u2(self.utf8(name)) + u2(self.utf8(descriptor)))
        return self.add(b"\x0a" + u2(cls) + u2(pair))

    def method(self, name, code, descriptor="()I", *, stack=8, locals_=8,
               flags=0x0009, nested=(), handlers=()):
        attrs = b"".join(u2(self.utf8(key)) + u4(len(value)) + value for key, value in nested)
        payload = (u2(stack) + u2(locals_) + u4(len(code)) + code + u2(len(handlers))
                   + b"".join(b"".join(u2(v) for v in h) for h in handlers)
                   + u2(len(nested)) + attrs)
        self.methods.append(u2(flags) + u2(self.utf8(name)) + u2(self.utf8(descriptor))
                            + u2(1) + u2(self.code_name) + u4(len(payload)) + payload)
        return self

    def build(self):
        return (b"\xca\xfe\xba\xbe" + u2(0) + u2(self.major)
                + u2(len(self.pool) + 1) + b"".join(self.pool)
                + u2(0x0021) + u2(self.this) + u2(self.super) + u2(0) + u2(0)
                + u2(len(self.methods)) + b"".join(self.methods) + u2(0))
