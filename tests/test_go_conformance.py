"""Adapter unit checks do not require or silently skip a Go/PCC compiler."""
import importlib.util
from pathlib import Path
import sys

import pytest

SCRIPTS = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPTS))
import conformance_ledger as ledger
import go_conformance as adapter
from language_feature_ledger import LedgerError


@pytest.mark.parametrize("recipe,expectation", [("run", "run"), ("compile", "accept"), ("errorcheck", "reject")])
def test_supported_directives(recipe, expectation):
    source = f'// {recipe}\npackage main\nfunc main() {{ var x int; if x {{}} }} // ERROR "bool"\n'.encode()
    result = adapter.parse_directive(source)
    assert result["supported"]
    assert result["action"] == recipe
    assert result["errors"] == [{"line": 3, "pattern": "bool"}]


@pytest.mark.parametrize("source,reason", [
    ('// run -race\npackage main', "flags/arguments"),
    ('// errorcheck -0\npackage main', "flags/arguments"),
    ('//go:build linux\n// run\npackage main', "constraint"),
    ('// +build linux\n// run\npackage main', "constraint"),
    ('// compiledir\npackage main', "recipe"),
    ('// runoutput\npackage main', "recipe"),
    ('// skip\npackage main', "recipe"),
    ('\n// run\npackage main', "leading newline"),
    ('// run\npackage main\nimport "fmt"', "import graph"),
    ('// run\npackage main\n//go:noinline\nfunc f() {}', "pragma"),
    ('// errorcheck\npackage main\n// ERRORAUTO "error"', "autogenerated"),
    ('// errorcheck\npackage main\n// GC_ERROR "error"', "conditional"),
    ('// errorcheck\npackage main\n// ERROR "LINE+1"', "LINE"),
    ('// errorcheck\npackage main\n// ERROR "(?=x)"', "RE2"),
    ('// errorcheck\npackage main\n// ERROR "[[:alpha:]]"', "RE2"),
    ('// errorcheck\npackage main\n// ERROR "error" trailing', "trailing"),
    ('// errorcheck\npackage main\n// ERROR', "requires"),
])
def test_unsupported_is_explicit(source, reason):
    result = adapter.parse_directive(source.encode())
    assert not result["supported"]
    assert any(reason in item for item in result["reasons"])


def test_disabled_annotations_and_gccgo_are_not_gc_expectations():
    parsed = adapter.parse_directive(b'// errorcheck\npackage main\n//// ERROR "disabled"\n// GCCGO_ERROR "other"\n// ERROR "bool|int"')
    assert parsed["supported"]
    assert parsed["errors"] == [{"line": 5, "pattern": "bool|int"}]


@pytest.mark.parametrize("output,wanted", [
    (b"test.go:12:4: Go: if condition requires bool\n", "passed"),
    (b"/original/test.go:12: non-boolean condition in if statement\n", "passed"),
    (b"test.go:13: condition must be bool\n", "failed"),
    (b"test.go:12: unsupported package\n", "failed"),
    (b"test.go:12: condition must be bool\ntest.go:14: extra\n", "failed"),
    (b"test.go:12: condition must be bool\n\tcontext\n", "unsupported"),
    (b"other.go:12: condition must be bool\n", "unsupported"),
    (b"Traceback: bool\n", "unsupported"),
    (b"", "failed"),
])
def test_errorcheck_is_not_rejection_equivalence(output, wanted):
    assert adapter.errorcheck([{"line": 12, "pattern": "bool"}], output, "test.go") == wanted


def test_multiple_errors_same_line_consume_matching_diagnostics():
    wanted = [{"line": 2, "pattern": "one"}, {"line": 2, "pattern": "two"}]
    assert adapter.errorcheck(wanted, b"a.go:2: one\na.go:2: two\n", "a.go") == "passed"
    assert adapter.errorcheck(wanted, b"a.go:2: one\n", "a.go") == "failed"


def test_path_cannot_escape_source_tree(tmp_path):
    with pytest.raises(ValueError, match="missing or escaping"):
        adapter.original(tmp_path, "../secret.go")


def test_missing_tool_is_blocked_not_skipped(tmp_path):
    result = adapter.process([str(tmp_path / "absent")], tmp_path, "absent", 1)
    assert result["outcome"] == "blocked"
    assert "missing/unusable tool" in result["reason"]


def test_timeout_is_not_rejection(tmp_path):
    result = adapter.process([sys.executable, "-c", "import time; time.sleep(5)"], tmp_path, "sleep", .02)
    assert adapter.compile_phase(result)["outcome"] == "blocked"
    assert result["timed_out"]


def test_required_checks_gate_all_generic_expectations():
    phase = {"outcome": "rejected"}
    row = {"compile": phase, "reference": {"compile": phase}}
    test = {"expectation": "reject", "required_checks": [adapter.CHECK]}
    for status in (None, "not_run", "unsupported", "failed"):
        row["checks"] = {} if status is None else {adapter.CHECK: status}
        assert not ledger.test_passed(row, test)
    row["checks"] = {adapter.CHECK: "passed"}
    assert ledger.test_passed(row, test)
    assert ledger.test_passed({"compile": phase, "reference": {"compile": phase}}, {"expectation": "reject"})


def ledger_fixtures():
    spec = importlib.util.spec_from_file_location("ledger_fixtures", Path(__file__).with_name("test_language_feature_ledger.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.suite(), module.run()


@pytest.mark.parametrize("bad", ["typo", "", 42])
def test_unknown_required_check_rejected(bad):
    suite, _ = ledger_fixtures()
    suite["tests"][0]["required_checks"] = [bad]
    with pytest.raises(LedgerError):
        ledger.validate_suite(suite)


def test_unknown_check_and_outcome_rejected():
    suite, run = ledger_fixtures()
    suite["tests"][0]["required_checks"] = [adapter.CHECK]
    for check, result in (("unknown", "passed"), (adapter.CHECK, "skipped")):
        run["results"][0]["checks"] = {check: result}
        with pytest.raises(LedgerError):
            ledger.validate_run(run, suite)


@pytest.mark.parametrize("status", ["passed", "failed", "unsupported", "not_run"])
def test_adapter_boolean_cannot_authorize_baseline_export(status):
    suite, run = ledger_fixtures()
    suite["tests"][0]["required_checks"] = [adapter.CHECK]
    run["results"][0]["checks"] = {adapter.CHECK: status}
    # Even a passed adapter flag and otherwise valid observations cannot replace
    # recognized assertion-proof replay over retained official directives.
    with pytest.raises(LedgerError, match="adapter-required assertion-proof replay is not supported"):
        ledger.passed_allowlist(run, suite, {"records": []})


