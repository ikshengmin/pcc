@pytest.mark.parametrize("row,expected", [
    ({"adapter_reasons": ["compiledir"]}, "harness_recipe"),
    ({"compile": {"outcome": "blocked", "reason": "missing tool"}}, "missing_tool"),
    ({"compile": {"outcome": "blocked", "reason": "timeout"}}, "execution_infrastructure"),
    ({"diagnostic_category": "frontend_unsupported"}, "frontend_unsupported"),
    ({"diagnostic_category": "library_runtime_dependency"}, "library_runtime_dependency"),
    ({}, "semantic_or_output_mismatch"),
])
def test_harness_and_language_blockers_are_separate(row, expected):
    row = {"compile": {"outcome": "not_run"}, "run": {"outcome": "not_run"}, **row}
    assert adapter.blocker_category(row) == expected


def test_manifest_rejects_changed_pinned_source(tmp_path, monkeypatch):
    (tmp_path / "VERSION").write_text(adapter.RELEASE + "\n")
    (tmp_path / "LICENSE").write_bytes(b"unit-test license, not official source")
    monkeypatch.setattr(adapter, "LICENSE_SHA256", adapter.sha((tmp_path / "LICENSE").read_bytes()))
    source = tmp_path / adapter.REPRESENTATIVE[0]
    source.parent.mkdir(parents=True)
    source.write_bytes(b"// run\npackage main\nfunc main() {}")
    with pytest.raises(ValueError, match="differs from pinned"):
        adapter.make_suite(tmp_path, [adapter.REPRESENTATIVE[0]])


@pytest.mark.parametrize("kind,code,message,unsupported", [
    ("invalid", None, "condition requires bool", False),
    ("invalid", "go.invalid-condition", "condition requires bool", False),
    ("unsupported", "go.unsupported.bool", "unimplemented bool operation", True),
    (None, None, "unsupported builtin panic", True),
    ("unclassified", None, "unsupported builtin panic", True),
    ("invalid", None, "unsupported builtin panic", True),
    (None, None, "slice requires shared-runtime storage", True),
    (None, None, "condition requires bool", False),
])
def test_diagnostic_kinds_are_not_confused_with_semantic_rejections(kind, code, message, unsupported):
    error = ValueError(message)
    error.kind, error.code, error.line, error.column = kind, code, 3, 4
    info = adapter.diagnostic_info(error)
    assert info["implementation_unsupported"] == unsupported
    assert info["code"] == code  # Never invent a code for a legacy message.
