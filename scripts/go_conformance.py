def sha(data):
    return hashlib.sha256(data).hexdigest()


def digest_file(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def original(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError("missing or escaping original source: " + relative)
    return path.read_bytes()


def parse_directive(data):
    """Import only explicit flag-free single-file recipes and a small RE2 subset.

    First-line selection and disabled //// annotations follow the pinned runner.
    Constraints, flags, ERRORAUTO/GC_ERROR, LINE substitutions, multiline context,
    nontrivial regex syntax and compiler pragmas are explicit unsupported outcomes.
    No importing or translating upstream compiler implementation is involved.
    """
    try:
        source = data.decode("utf-8")
    except UnicodeDecodeError:
        return {"action": "unknown", "supported": False, "reasons": ["non-UTF-8 source"]}
    reasons, recipe = [], ""
    if source.startswith("\n"):
        reasons.append("leading newline forbidden by upstream runner")
    for line in source.splitlines():
        if line.startswith(("//go:build", "// +build")):
            reasons.append("build constraints require target-aware selection")
            continue
        if line.strip():
            recipe = line.removeprefix("//").strip()
            break
    words = recipe.split()
    action = words[0] if words else "unknown"
    if action not in ("run", "compile", "errorcheck"):
        reasons.append("unsupported recipe: " + action)
    if len(words) != 1:
        reasons.append("recipe flags/arguments require upstream-specific semantics")
    if re.search(r"(?m)^\s*import\b", source):
        reasons.append("import graph/importcfg not supplied by single-file adapter")
    if re.search(r"(?m)^\s*//(?:go:| \+build)", source):
        reasons.append("compiler pragma or build constraint")
    errors = []
    for number, line in enumerate(source.splitlines(), 1):
        if "////" in line:
            continue
        if re.search(r"// (?:GC_ERROR|ERRORAUTO)\b", line):
            reasons.append("conditional/autogenerated error annotation")
        match = re.search(r'// ERROR\s+(.*)', line)
        if not match:
            continue
        tail = match[1]
        patterns = re.findall(r'"([^"\n]*)"', tail)
        if not patterns or re.sub(r'"[^"\n]*"', '', tail).strip():
            reasons.append("malformed or trailing error annotation context")
        for pattern in patterns:
            # Only literal text, .*, alternatives, and escaped punctuation. This
            # avoids claiming Python re implements Go's RE2 dialect generally.
            rest = re.sub(r"\\[^A-Za-z0-9]", "", pattern).replace(".*", "")
            if "LINE" in pattern or re.search(r"[\\\[\](){}?+*^$]", rest):
                reasons.append("unsupported RE2 expression or LINE substitution")
                continue
            try:
                re.compile(pattern)
            except re.error:
                reasons.append("invalid error regular expression")
                continue
            errors.append({"line": number, "pattern": pattern})
    if action == "errorcheck" and not errors:
        reasons.append("errorcheck requires supported ERROR expectations")
    return {"action": action, "recipe": recipe, "supported": not reasons,
            "reasons": sorted(set(reasons)), "errors": errors}


def errorcheck(expected, output, filename):
    """All expected line/message patterns must match; no unrelated diagnostics.

    Context/continuation lines are unsupported, never discarded to manufacture a
    pass. A feature-not-implemented diagnostic cannot pass merely by rejecting.
    """
    messages = []
    for line in output.decode("utf-8", "replace").splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r"(.+?):(\d+)(?::\d+)?:\s*(.*)", line)
        if not match or Path(match[1]).name != filename:
            return "unsupported"
        messages.append((int(match[2]), match[3]))
    remaining = list(messages)
    for wanted in expected:
        matched = [item for item in remaining if item[0] == wanted["line"]
                   and re.search(wanted["pattern"], item[1])]
        if not matched:
            return "failed"
        remaining = [item for item in remaining if item not in matched]
    return "failed" if remaining else "passed"


def make_suite(root, paths=REPRESENTATIVE):
    if original(root, "VERSION").decode().splitlines()[0] != RELEASE:
        raise ValueError("Go source version mismatch")
    if sha(original(root, "LICENSE")) != LICENSE_SHA256:
        raise ValueError("Go source license identity mismatch")
    tests = []
    for relative in paths:
        data = original(root, relative)
        if relative not in PINNED_INPUTS or sha(data) != PINNED_INPUTS[relative]:
            raise ValueError("selected source differs from pinned official release: " + relative)
        directive = parse_directive(data)
        action = directive["action"]
        if action not in ("run", "compile", "errorcheck"):
            raise ValueError("suite selection must have a recognized expectation")
        expected_path = str(Path(relative).with_suffix(".out"))
        expected = root / expected_path
        output_sha = sha(expected.read_bytes() if expected.is_file() else b"")
        wanted_output_sha = HELLO_OUTPUT_SHA256 if relative == "test/helloworld.go" else sha(b"")
        if output_sha != wanted_output_sha or (expected.is_file() != (relative == "test/helloworld.go")):
            raise ValueError("expected-output fixture differs from pinned release: " + expected_path)
        tests.append({"id": relative, "path": relative, "sha256": sha(data),
                      "bytes": len(data), "feature_ids": [],
                      "expectation": {"run": "run", "compile": "accept", "errorcheck": "reject"}[action],
                      "required_checks": [CHECK], "directive": directive,
                      "license": "BSD-3-Clause", "license_path": "LICENSE",
                      "copyright": next((line.removeprefix("// ") for line in data.decode().splitlines()
                                         if line.startswith("// Copyright")), "not present"),
                      "source_url": f"https://go.googlesource.com/go/+/{COMMIT}/{relative}",
                      "expected_output": {"path": expected_path if expected.is_file() else None,
                                          "sha256": output_sha}})
    content = [{key: row[key] for key in ("path", "sha256", "expected_output", "required_checks", "directive")}
               for row in tests]
    suite = {"schema_version": 1, "id": "go-official-test-representative", "language": "go",
             "version": RELEASE, "license": "BSD-3-Clause", "license_sha256": LICENSE_SHA256,
             "source_url": "https://go.dev/dl/go1.27.3.linux-amd64.tar.gz",
             "source_revision": COMMIT, "archive_sha256": ARCHIVE_SHA256,
             "source_sha256": sha(json.dumps(content, sort_keys=True).encode()),
             "source_unchanged": True, "inventory_complete": False, "scope": "official",
             "inventory_scope": "five explicitly selected test/ driver sources; not full suite or stdlib",
             "adapter": "scripts/go_conformance.py", "tests": tests}
    return validate_suite(suite, root)


def inventory(root, archive):
    """Verify complete release-distributed test/ tree without extracting a copy."""
    if digest_file(archive) != ARCHIVE_SHA256:
        raise ValueError("official release archive SHA256 mismatch")
    if original(root, "VERSION").decode().splitlines()[0] != RELEASE:
        raise ValueError("Go source version mismatch")
    if sha(original(root, "LICENSE")) != LICENSE_SHA256:
        raise ValueError("source license differs from pinned release")
    if sha(original(root, "src/cmd/internal/testdir/testdir_test.go")) != RUNNER_SHA256:
        raise ValueError("source runner differs from pinned driver-directory contract")
    expected = {}
    with tarfile.open(archive, "r|gz") as bundle:
        for member in bundle:
            if member.name.startswith("go/test/") and member.isfile():
                expected[member.name[3:]] = sha(bundle.extractfile(member).read())
    if not expected:
        raise ValueError("archive has no test/ source inputs")
    actual = {str(path.relative_to(root)): digest_file(path)
              for path in (root / "test").rglob("*") if path.is_file()}
    missing = sorted(expected.keys() - actual.keys())
    extra = sorted(actual.keys() - expected.keys())
    changed = sorted(path for path in expected.keys() & actual.keys() if expected[path] != actual[path])
    rows = []
    for directory in DIRECTORIES:
        folder = root / "test" / directory
        if not folder.is_dir():
            missing.append("test/" + directory + "/")
            continue
        for path in sorted(folder.glob("*.go")):
            if not path.name.startswith("."):
                rows.append({"path": str(path.relative_to(root)), "sha256": digest_file(path),
                             **parse_directive(path.read_bytes())})
    # These are source-file inventory counts, NOT unittest counts or package passes.
    stdtests = sorted(str(p.relative_to(root)) for p in (root / "src").rglob("*_test.go")
                     if "cmd" != p.relative_to(root / "src").parts[0])
    return {"schema_version": 1, "version": RELEASE, "source_revision": COMMIT,
            "archive_sha256": ARCHIVE_SHA256, "license_sha256": sha(original(root, "LICENSE")),
            "inventory_complete": not (missing or extra or changed),
            "scope": "release-distributed test/ tree, official driver directory enumeration",
            "test_tree_file_count": len(expected), "driver_test_count": len(rows),
            "missing_inputs": missing, "extra_inputs": extra, "changed_inputs": changed,
            "recipes": dict(sorted(Counter(row["action"] for row in rows).items())),
            "adapter_supported_count": sum(row["supported"] for row in rows),
            "standard_library": {"inventory_complete": False, "source_file_count": len(stdtests),
                                 "scope": "src/**/*_test.go excluding cmd; no package/build-tag/test-function selection",
                                 "execution": "not_run"}, "tests": rows}


def process(command, cwd, prefix, timeout, env=None):
    out, err = cwd / (prefix + ".stdout"), cwd / (prefix + ".stderr")
    try:
        result = run_process(command, cwd=cwd, stdout=out, stderr=err, timeout=timeout, env=env)
    except OSError as error:
        return {"outcome": "blocked", "reason": f"missing/unusable tool: {type(error).__name__}"}
    write_json(cwd / (prefix + ".receipt.json"), {"command": command, **result})
    phase = {"outcome": "completed", "exit_code": result["returncode"],
             "stdout_sha256": digest_file(out), "stderr_sha256": digest_file(err)}
    if result["timed_out"] or result["returncode"] < 0:
        phase.update(outcome="blocked", reason="timeout or signal", timed_out=result["timed_out"])
    return phase


def compile_phase(phase):
    if phase["outcome"] != "blocked":
        phase["outcome"] = "accepted" if phase["exit_code"] == 0 else "rejected"
    return phase


def compiler_identity(root, revision):
    """Freeze the whole Python compiler input closure, not a guessed public HEAD."""
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                          capture_output=True, timeout=6, check=True).stdout.decode().strip()
    if head != revision:
        raise ValueError("compiler revision does not match selected source checkout")
    status = subprocess.run(["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"],
                            capture_output=True, timeout=6, check=True).stdout
    if status:
        raise ValueError("compiler checkout has tracked changes; freeze an immutable compiler view")
    files = sorted((root / "pcc").rglob("*.py")) + [root / "tests/go/owned_execution.py"]
    if not files or not (root / "pcc/frontends/go/__init__.py").is_file():
        raise ValueError("missing PCC Go compiler inputs")
    hashes = {str(path.relative_to(root)): digest_file(path) for path in files}
    return {"revision": head, "source_hashes": hashes,
            "closure_sha256": sha(json.dumps(hashes, sort_keys=True).encode())}


def blocker_category(row):
    if row.get("adapter_reasons"):
        return "harness_recipe"
    phases = [row["compile"], row["run"]]
    phases += [row.get("reference", {}).get(key, {}) for key in ("compile", "run")]
    if any(phase.get("outcome") == "blocked" and "tool" in phase.get("reason", "") for phase in phases):
        return "missing_tool"
    if any(phase.get("outcome") == "blocked" for phase in phases):
        return "execution_infrastructure"
    return row.get("diagnostic_category", "semantic_or_output_mismatch")


def diagnostic_info(error):
    code = getattr(error, "code", None)
    # Legacy/mixed sites remain unclassified, even on some coded compilers.
    # Conservative inspection only excludes false passes and invents no code.
    kind = getattr(error, "kind", None)
    capability = (kind == "unsupported" or bool(re.search(
        r"unsupported|not implemented|unimplemented|requires? shared", str(error))))
    dependency = bool(re.search(r"shared.?runtime|import source unavailable", str(error)))
    return {"kind": "GoDiagnostic", "code": code,
            "feature_id": getattr(error, "feature_id", None),
            "implementation_unsupported": capability,
            "category": "library_runtime_dependency" if dependency else
                        "frontend_unsupported" if capability else "semantic_diagnostic",
            "line": error.line, "column": error.column}


def worker(args):
    """PCC-only process. Source and main stay unchanged; no reference fallback."""
    import builtins
    import subprocess
    sys.path.insert(0, str(args.pcc_source))
    original_import = builtins.__import__
    def owned_import(name, *positional, **keywords):
        if name == "llvmlite" or name.startswith("llvmlite."):
            raise RuntimeError("external LLVM import forbidden in owned Go compile")
        return original_import(name, *positional, **keywords)
    def no_process(*positional, **keywords):
        raise RuntimeError("external process forbidden in owned Go compile")
    builtins.__import__ = owned_import
    subprocess.Popen = subprocess.run = no_process
    from pcc.frontends.go import GoDiagnostic, compile_go_sources, DEFAULT_TARGET
    from tests.go.owned_execution import compile_owned, write_artifact
    data = args.input.read_bytes()
    units = ((args.input.name, data.decode("utf-8")),)
    try:
        if args.action == "run":
            write_artifact(compile_owned(units), args.output)
        else:
            from pcc.backend.owned_object_emit import emit_owned_object
            args.output.write_bytes(emit_owned_object(str(compile_go_sources(units)), DEFAULT_TARGET))
    except GoDiagnostic as error:
        write_json(args.diagnostic, diagnostic_info(error))
        print(str(error), file=sys.stderr)
        return 1
    write_json(args.diagnostic, {"kind": "accepted", "input_sha256": sha(data)})
    return 0


def execute(args):
    suite = json.loads(args.manifest.read_text())
    validate_suite(suite, args.go_src)
    if suite != make_suite(args.go_src, [row["path"] for row in suite["tests"]]):
        raise ValueError("manifest directive/output/provenance differs from original inputs")
    if not 1 <= len(suite["tests"]) <= 6:
        raise ValueError("bounded shard requires 1..6 tests; full-suite execution needs separate admission")
    if sys.platform != "linux" or platform.machine() != "x86_64":
        raise ValueError("owned adapter currently supports real Linux x86_64 pcc0 only")
    for source_root in (Path(__file__).resolve().parents[1], args.pcc_source, args.go_src):
        if args.out.resolve().is_relative_to(source_root.resolve()):
            raise ValueError("outputs must be outside source repositories")
    args.out.mkdir(parents=True, exist_ok=False)
    frozen_compiler = compiler_identity(args.pcc_source, args.compiler_revision)
    write_json(args.out / "compiler-identity.json", frozen_compiler)
    write_json(args.out / "adapter-identity.json", {
        "source_hashes": {str(path.name): digest_file(path) for path in (
            Path(__file__), Path(__file__).with_name("conformance_ledger.py"),
            Path(__file__).with_name("language_feature_ledger.py"),
            Path(__file__).parent / "cpython_conformance/run.py")},
        "manifest_sha256": digest_file(args.manifest), "python": sys.version})
    env = dict(os.environ, GOTOOLCHAIN="local", GOPROXY="off", GOSUMDB="off", GOENV="off",
               GOWORK="off", GO111MODULE="off", CGO_ENABLED="0", GOFLAGS="", GOOS="linux",
               GOARCH="amd64", GOCACHE=str(args.reference_cache), GOMAXPROCS="2", GOEXPERIMENT="",
               GOROOT=str(args.go_src), GODEBUG="")
    version = process([str(args.go), "version"], args.out, "reference-version", args.timeout, env)
    version_ok = (version.get("exit_code") == 0 and version["outcome"] != "blocked"
                  and (args.out / "reference-version.stdout").read_bytes().strip()
                  == b"go version go1.27.3 linux/amd64")
    write_json(args.out / "reference-identity.json", {
        "role": "external_reference", "version_process": version,
        "go_sha256": digest_file(args.go) if args.go.is_file() else None,
        "compile_sha256": digest_file(args.go_src / "pkg/tool/linux_amd64/compile")
                          if (args.go_src / "pkg/tool/linux_amd64/compile").is_file() else None,
        "source_archive_sha256": suite["archive_sha256"]})
    run = {"schema_version": 1, "suite_id": suite["id"], "suite_version": suite["version"],
           "suite_source_sha256": suite["source_sha256"], "compiler_revision": args.compiler_revision,
           "mode": "pcc0", "platform": "linux-x86_64", "backend": "self",
           "gc": "not_exercised", "results": []}
    for index, test in enumerate(suite["tests"]):
        directory = args.out / f"case-{index:02d}"
        directory.mkdir()
        data = original(args.go_src, test["path"])
        source = directory / Path(test["path"]).name
        source.write_bytes(data)
        action = test["directive"]["action"]
        row = {"test_id": test["id"], "input_sha256": sha(data), "project": "golang/go",
               "compile": {"outcome": "not_run"}, "run": {"outcome": "not_run"},
               "diagnostic_codes": [], "blocker_feature_ids": [], "checks": {CHECK: "not_run"}}
        run["results"].append(row)
        if not test["directive"]["supported"]:
            row.update(adapter_reasons=test["directive"]["reasons"], checks={CHECK: "unsupported"})
            continue
        binary, diagnostic = directory / "owned", directory / "diagnostic.json"
        command = [sys.executable, str(Path(__file__).resolve()), "_compile", "--pcc-source",
                   str(args.pcc_source), "--input", str(source), "--output", str(binary),
                   "--action", action, "--diagnostic", str(diagnostic)]
        row["compile"] = compile_phase(process(command, directory, "pcc-compile", args.timeout))
        if diagnostic.is_file():
            details = json.loads(diagnostic.read_text())
            if details.get("code"):
                row["diagnostic_codes"] = [details["code"]]
            if details.get("feature_id"):
                row["blocker_feature_ids"] = [details["feature_id"]]
            row["diagnostic_identity"] = "stable_code" if details.get("code") else "message_only_or_none"
            if details.get("category"):
                row["diagnostic_category"] = details["category"]
        elif row["compile"]["outcome"] != "blocked":
            row["compile"].update(outcome="blocked", reason="compiler worker failed without structured completion")
        reference = {"name": "Go", "version": RELEASE, "platform": "linux-x86_64",
                     "role": "external_reference", "input_sha256": sha(data),
                     "kind": {"run": "native_execution", "compile": "metadata_typecheck",
                              "errorcheck": "expected_rejection"}[action],
                     "compile": {"outcome": "blocked", "reason": "missing or mismatched official Go tool"},
                     "run": {"outcome": "not_run"}}
        row["reference"] = reference
        oracle = directory / "reference"
        if version_ok:
            command = ([str(args.go), "build", "-p=2", "-o", str(oracle), str(source)] if action == "run"
                       else [str(args.go), "tool", "compile", "-p=p", "-e", "-C", "-d=panic",
                             "-d=ssa/check/on", "-o", str(oracle), str(source)])
            reference["compile"] = compile_phase(process(command, directory, "go-compile", args.timeout, env))
        if action == "run":
            for owner, executable, prefix in ((row, binary, "pcc-run"), (reference, oracle, "go-run")):
                if owner["compile"]["outcome"] == "accepted":
                    owner["run"] = process([str(executable)], directory, prefix, args.timeout, env)
            expected = test["expected_output"]
            # Separate streams remain raw. Nonempty combined-output cases are
            # supported only when at most one stream is nonempty (no invented ordering).
            verdicts = []
            for owner, prefix in ((row, "pcc-run"), (reference, "go-run")):
                if owner["run"]["outcome"] != "completed":
                    verdicts.append("failed")
                    continue
                stdout, stderr = (directory / (prefix + ".stdout")).read_bytes(), (directory / (prefix + ".stderr")).read_bytes()
                verdicts.append("unsupported" if stdout and stderr else
                                "passed" if owner["run"]["exit_code"] == 0 and sha((stdout + stderr).replace(b"\r\n", b"\n")) == expected["sha256"] else "failed")
        elif action == "errorcheck":
            verdicts = []
            for owner, prefix in ((row, "pcc-compile"), (reference, "go-compile")):
                if owner["compile"]["outcome"] != "rejected":
                    verdicts.append("failed")
                    continue
                output = (directory / (prefix + ".stdout")).read_bytes() + (directory / (prefix + ".stderr")).read_bytes()
                if owner is row and diagnostic.is_file() and json.loads(diagnostic.read_text()).get("implementation_unsupported"):
                    verdicts.append("failed")
                else:
                    verdicts.append(errorcheck(test["directive"]["errors"], output, source.name))
        else:
            verdicts = ["passed" if owner["compile"]["outcome"] == "accepted" else "failed"
                        for owner in (row, reference)]
        row["checks"][CHECK] = "unsupported" if "unsupported" in verdicts else "passed" if all(v == "passed" for v in verdicts) else "failed"
        row["directive_verdicts"] = dict(zip(("pcc", "reference"), verdicts))
        if source.read_bytes() != data:
            raise ValueError("test changed original source input")
        write_json(args.out / "run.json", run)
    write_json(args.out / "run.json", run)
    summary = summarize_run(run, suite)
    failures = [row for row in run["results"] if row["test_id"] not in summary["passed"]]
    summary["blocker_categories"] = dict(sorted(Counter(blocker_category(row) for row in failures).items()))
    if compiler_identity(args.pcc_source, args.compiler_revision) != frozen_compiler:
        raise ValueError("compiler inputs changed during shard; results cannot qualify")
    write_json(args.out / "summary.json", summary)
    print(json.dumps(summary, sort_keys=True))
    return 0 if len(summary["passed"]) == len(suite["tests"]) else 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="operation", required=True)
    for operation in ("manifest", "inventory", "run"):
        command = sub.add_parser(operation)
        command.add_argument("--go-src", type=Path, required=True)
        command.add_argument("--out", type=Path, required=True)
        if operation == "inventory":
            command.add_argument("--archive", type=Path, required=True)
        if operation == "run":
            command.add_argument("--manifest", type=Path, required=True)
            command.add_argument("--pcc-source", type=Path, required=True)
            command.add_argument("--compiler-revision", required=True)
            command.add_argument("--go", type=Path, required=True)
            command.add_argument("--reference-cache", type=Path, required=True)
            command.add_argument("--timeout", type=float, default=6)
    command = sub.add_parser("_compile")
    for name in ("pcc-source", "input", "output", "diagnostic"):
        command.add_argument("--" + name, type=Path, required=True)
    command.add_argument("--action", choices=("run", "compile", "errorcheck"), required=True)
    args = parser.parse_args(argv)
    if args.operation == "_compile":
        return worker(args)
    if args.operation == "run":
        if not 0 < args.timeout <= 6:
            parser.error("bounded per-process timeout must be in (0, 6] seconds")
        return execute(args)
    value = make_suite(args.go_src) if args.operation == "manifest" else inventory(args.go_src, args.archive)
    write_json(args.out, value)
    return 0


