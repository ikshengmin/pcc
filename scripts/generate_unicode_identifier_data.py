"""Generate owned Unicode 17 identifier/normalization data from CPython 3.15.

The compiler consumes only the emitted packed bytes, not host unicodedata.
Unicode Character Database: https://www.unicode.org/versions/Unicode17.0.0/
Data license: https://www.unicode.org/license.txt
"""
from pathlib import Path
import struct
import sys
import unicodedata


def ranges(values):
    result = []
    for value in values:
        if result and result[-1] + 1 == value:
            result[-1] = value
        else:
            result.extend((value, value))
    return result


def packed(values, width="I"):
    return struct.pack("<" + width * len(values), *values)


def main():
    if sys.version_info[:2] != (3, 15) or unicodedata.unidata_version != "17.0.0":
        raise SystemExit("requires CPython 3.15 with Unicode 17.0.0")
    starts, continues, decompositions, combining, compositions = [], [], {}, {}, {}
    for code in range(0x110000):
        char = chr(code)
        if code >= 128:
            if char.isidentifier():
                starts.append(code)
            if ("A" + char).isidentifier():
                continues.append(code)
        category = unicodedata.combining(char)
        if category:
            combining[code] = category
        raw = unicodedata.decomposition(char)
        # Hangul decomposition/composition is algorithmic in the consumer.
        if raw and not 0xAC00 <= code < 0xD7A4:
            fields = raw.split()
            canonical = not fields[0].startswith("<")
            if not canonical:
                fields = fields[1:]
            parts = tuple(int(field, 16) for field in fields)
            decompositions[code] = parts
            if canonical and len(parts) == 2:
                pair = "".join(chr(part) for part in parts)
                if unicodedata.normalize("NFC", pair) == char:
                    compositions[(parts[0] << 21) | parts[1]] = code
    keys = sorted(decompositions)
    offsets, values = [0], []
    for key in keys:
        values.extend(decompositions[key])
        offsets.append(len(values))
    combining_keys = sorted(combining)
    composition_keys = sorted(compositions)
    tables = {
        "XID_START": packed(ranges(starts)),
        "XID_CONTINUE": packed(ranges(continues)),
        "DECOMPOSITION_KEYS": packed(keys),
        "DECOMPOSITION_OFFSETS": packed(offsets),
        "DECOMPOSITION_VALUES": packed(values),
        "COMBINING_KEYS": packed(combining_keys),
        "COMBINING_VALUES": bytes(combining[key] for key in combining_keys),
        "COMPOSITION_KEYS": packed(composition_keys, "Q"),
        "COMPOSITION_VALUES": packed([compositions[key] for key in composition_keys]),
    }
    lines = [
        '"""Generated by scripts/generate_unicode_identifier_data.py.',
        "CPython 3.15 / Unicode 17.0.0; little-endian packed data.",
        "Unicode data license: https://www.unicode.org/license.txt",
        '"""',
        'UNICODE_VERSION = "17.0.0"',
    ]
    for name, payload in tables.items():
        lines.extend(("", name + " = ("))
        for offset in range(0, len(payload), 32):
            lines.append("    " + repr(payload[offset:offset + 32]))
        lines.append(")")
    target = Path(__file__).resolve().parents[1] / "pcc/frontends/python/_unicode_identifier_data.py"
    target.write_text("\n".join(lines) + "\n", encoding="ascii")
    print("packed bytes:", sum(len(value) for value in tables.values()))
    print("generated:", target)


if __name__ == "__main__":
    main()
