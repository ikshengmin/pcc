@c_abi_export("pcc_ascii_image_char")
def ascii_image_char(c: i64) -> c_ptr:
    if c < 0 or c >= 128:
        return null()
    # The table above has six words per object, derived from PyStrObject.
    out = ptr_add(global_addr("pcc_ascii_image_chars"), c * 48)
    bits = global_addr("pcc_ascii_image_registered")
    word: i64 = logical_shift_right_i64(c, 6) * 8
    mask: i64 = 1 << (c & 63)
    if (atomic_load_i64(bits, word, "acquire") & mask) != 0:
        return out
    if pcc_gc_pointer_register(out) < 0:
        return null()
    atomic_rmw_i64("or", bits, word, mask, "release")
    return out
